ALL_TARGETED_PLATFORMS: Dict[str, PlatformConfig] = {
    **TARGETED_ATS_PLATFORMS,
    **TARGETED_JOB_PORTALS,
}


def classify_source_url(url: str) -> Optional[PlatformConfig]:
    """
    Identifies whether a given URL belongs to one of the 21 ATS Platforms
    or 14 Job Portals. Returns the matching PlatformConfig or None.
    """
    if not url:
        return None
    u = url.lower()

    # Check ATS Platforms first
    for cfg in TARGETED_ATS_PLATFORMS.values():
        if any(pat in u for pat in cfg.domain_patterns):
            return cfg

    # Check Job Portals second
    for cfg in TARGETED_JOB_PORTALS.values():
        if any(pat in u for pat in cfg.domain_patterns):
            return cfg

    return None


def get_ats_names() -> List[str]:
    """Returns canonical display names of all 21 ATS platforms."""
    return [cfg.name for cfg in TARGETED_ATS_PLATFORMS.values()]


def get_portal_names() -> List[str]:
    """Returns canonical display names of all 14 Job Portals."""
    return [cfg.name for cfg in TARGETED_JOB_PORTALS.values()]
